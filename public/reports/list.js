// Reports (UC-013, UC-014): generate an accreditation report (FR-034, BR-007: administrators and
// management only) or a department report (FR-035), and open earlier reports.
import { api } from '/js/api.js';
import { escapeHtml, fmtDateTime } from '/js/format.js';
import { initPage, showFlash, clearFlash, renderApiFailure } from '/js/layout.js';
import { yearRangeFields, readYearRange } from '/js/filters.js';

const TYPE_NAMES = { ACCREDITATION: 'Accreditation and ranking', DEPARTMENT: 'Department summary' };

const page = await initPage({
  active: 'reports',
  title: 'Reports',
  subtitle: 'Built from verified publications only',
  roles: ['RESEARCH_ADMIN', 'INSTITUTE_MGMT', 'HOD'],
});

if (page) {
  const { me, content } = page;
  const isHod = me.user.role === 'HOD';
  const year = new Date().getFullYear();
  load();

  async function load() {
    content.innerHTML = '<div class="state">Loading…</div>';
    try {
      const [{ reports }, { departments }] = await Promise.all([api('GET', '/api/reports'), api('GET', '/api/departments')]);
      render(reports, departments);
    } catch (err) {
      renderApiFailure(err, content, 'The reports could not be loaded.', load);
    }
  }

  function render(reports, departments) {
    const myDept = departments.find((d) => d.code === me.user.department);
    content.innerHTML = `
      <h2 style="margin-top:0">Generate a report</h2>
      <form class="box" id="gen-form">
        <div class="filter-bar" style="margin:0">
          <label class="inline-field">Report
            <select name="type">
              ${isHod ? '' : '<option value="ACCREDITATION">Accreditation and ranking report</option>'}
              <option value="DEPARTMENT">Department research summary</option>
            </select></label>
          <label class="inline-field">Scope
            ${isHod
              ? `<strong>${escapeHtml(myDept ? myDept.name : me.user.departmentName || '')}</strong>`
              : `<select name="departmentId"><option value="">Whole institute</option>
                  ${departments.map((d) => `<option value="${d.id}">${escapeHtml(d.name)}</option>`).join('')}</select>`}
          </label>
          ${yearRangeFields({ yearFrom: year - 4, yearTo: year }, { required: true })}
          <button type="submit" class="btn btn-primary">Generate report</button>
        </div>
        <p class="note" style="margin-bottom:0">${isHod
          ? 'As Head of Department you can generate reports of your own department. Accreditation reports are generated by the research office or institute management.'
          : 'An accreditation report covers the whole institute or one department. A department summary needs one department.'}</p>
      </form>

      <h2>Generated reports</h2>
      ${reports.length ? `<div class="table-wrap"><table class="data">
        <thead><tr><th>ID</th><th>Report</th><th>Scope</th><th>Years</th><th>Generated</th><th>By</th><th></th></tr></thead>
        <tbody>${reports.map((r) => `<tr>
          <td class="nowrap">${escapeHtml(r.publicId)}</td><td>${escapeHtml(TYPE_NAMES[r.type])}</td>
          <td>${escapeHtml(r.departmentName || 'Whole institute')}</td><td class="nowrap">${r.yearFrom}–${r.yearTo}</td>
          <td class="nowrap">${escapeHtml(fmtDateTime(r.generatedAt))}</td><td>${escapeHtml(r.generatedByName)}</td>
          <td class="nowrap"><a href="/reports/${r.id}">Open</a> · <a href="/api/reports/${r.id}/export.csv">CSV</a></td></tr>`).join('')}
        </tbody></table></div>` : '<div class="state">No reports have been generated yet.</div>'}`;

    const form = content.querySelector('#gen-form');
    form.addEventListener('submit', async (e) => {
      e.preventDefault();
      clearFlash();
      const range = readYearRange(form, { required: true });
      if (range.error) return showFlash('error', range.error);
      const body = { type: form.elements.type.value, ...range };
      if (!isHod) body.departmentId = form.elements.departmentId.value || null;
      if (body.type === 'DEPARTMENT' && !isHod && !body.departmentId) return showFlash('error', 'Select a department for a department summary.');
      const btn = form.querySelector('button[type="submit"]');
      btn.disabled = true;
      try {
        const { report } = await api('POST', '/api/reports', body);
        window.location.href = `/reports/${report.id}`;
      } catch (err) {
        btn.disabled = false;
        showFlash('error', err.status === 403 || err.status === 422 ? err.message : 'The report could not be generated. Nothing was changed. Retry.');
      }
    });
  }
}
